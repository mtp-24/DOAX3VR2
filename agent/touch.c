/* agent.touch (on by default, both builds: the settings menu's "Touch*", from the next start, with
 * agent.touchhead; cvars.txt's agent.touch=0 the default off): the VR controller "touch" the games shipped without,
 * restored with the game's own functions and data (logs/research/touch/REPORT.md section 3.1).
 *
 * What is in the games: the VR scene (Fortune 0x46c7d0, Scarlet 0x46e580) positions every frame
 * each entry {int table index, shape} of the controller sphere list S+0xc0/+0xc8/+0xd0 (begin,
 * end, capacity; 16-byte entries) on the tracked controller (0x46f1f8 / 0x470fa8, the offsets and
 * radii from the table 0x7c9d90 / 0x7d15e0: two 7 cm spheres), tests them against the girls' body
 * spheres (touching S+0x81, touch event S+0x8d), rumbles, feeds the scene's "close contact"
 * reaction, and at scene exit (the S teardown 0x46c0d0 / 0x46de80) removes each shape from the
 * soft-body world, releases it, sets end = begin and later frees the vector's storage to the
 * game's allocator. Nothing ever fills the list: the step that made the two spheres was cut.
 *
 * Here, that step only: on the game's main thread at the start of its loop (tick_frame, before
 * the update that runs the scene), once a scene, when S exists, the scene runs (S+0x154 == 1 and
 * S+0x160, its own gate at 0x46d3e5 / the same in Scarlet) and the list is as the S constructor
 * left it (begin, end, capacity all 0), for idx 0 and 1, as make_ywrk_sphere_collision
 * (0x3330b0 / 0x333460, the scripts' sphere collider) makes one:
 *   - shape = 0xb890(*factory, {0, 0, 0, 0, radius}): the shape comes back holding one reference
 *     (0x100 sets the count to 0 and adds 1); the game's sequence after it (0x3331a2..0x3331cb)
 *     leaves the count as it is, so that reference is the one the list entry keeps;
 *   - the world *world held (+1) for the calls, as the game does, then 0x2c60(world, shape) (the
 *     world takes its own reference), the filter made once by 0x3f70(world, {.., +0x20 = 3}, arg)
 *     into the game's own static handle under its own guard byte (shared with the scripts' path),
 *     0x3fa0(world, handle, shape, 1);
 *   - shape+0x10 = 0xffffffff80000000 under the shape's +0x50 lock;
 *   - placed where the scene loop will place it (0x2b0, the loop's own formula), so it does not
 *     sit at the world's origin until the scene's next frame (make_ywrk also positions at once);
 *   - {idx, shape} into storage from the game's allocator (*alloc, slot 0xc0, the tag the S
 *     constructor uses: 0x2c, 0x71, its name), because the teardown frees begin with slot 0xe0
 *     (0x46c718 / 0x46e4c8): a buffer of the agent's would be handed to the game's free.
 * The script path's other steps are not for these spheres: its direction (0x450; 0xb890 already
 * sets the shape's default) and its registration with the script module (0x334b60), whose
 * reference the list's takes the place of. Everything after (positioning, the hit test, rumble,
 * the reaction, removal at scene exit) is the game's. Not done (not in the data): the force-touch
 * byte S+0x80, any reaction to the stroke class S+0xb0.
 *
 * The head spheres (agent.touchhead, on by default with agent.touch=1; 0 leaves them out for a
 * comparison): the same mechanism for the player's head, also never filled. The list S+0x130/
 * +0x138/+0x140 (begin, end, capacity; {int index, shape}, 16 bytes), the table 0x7c9d70 /
 * 0x7d15c0: idx 0 radius 0.10 at the head, idx 1 radius 0.07 at (0, -0.02, -0.075) (2 cm down,
 * 7.5 cm forward: the face). The scene loop places them every frame, tracked or not, at
 * Fortune 0x4703f0..0x470502 / Scarlet 0x4721a0..0x4722b2: (H * (offset, 1)) * (1.0 / scale),
 * w 0, through 0x2b0, with H the head matrix the frame has just built and stored at S+0xe0..
 * +0x110 (rows x, y, z, position; 0x46ff1e / 0x471cce; the offset not scaled, unlike the
 * controller's), and the table in r12 (0x46f389 / 0x46f466, both paths). It does not test them
 * against the bodies (the head proximity flags S+0x120..0x122 test S+0x110 itself) and never
 * writes their +0x18 (left 0 by the shape's init, as a tracked controller sphere's): they only
 * push the soft bodies. The S teardown removes them from the world (0x46c3e0..0x46c4bd /
 * 0x46e190..0x46e26d) and frees the vector to the same allocator slot 0xe0 (0x46c65a / 0x46e40a).
 * Made here exactly as the controller's, once a scene, into S+0x130, once the head matrix has
 * been written (not all zero) so they never sit at the world's origin. Nothing the view uses is
 * read back or changed: the head pose, S+0xe0..+0x110 and the flags are only read.
 *
 * Before anything is called or written, every site this relies on is compared with the bytes of
 * both builds (the RIP-relative ones decode to this file's addresses): any difference and it
 * stays off (the head's own sites: only the head spheres off). Logged: each creation (shapes,
 * radii, counts), the game removing them, and every 10 s (on the agent's cvars thread) how
 * often the game's touching flag, touch event, rumble and head proximity flags came on.
 * SPDX-License-Identifier: GPL-3.0-or-later */
